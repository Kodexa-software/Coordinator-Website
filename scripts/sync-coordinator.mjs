// Pulls Coordinator's version and changelog into the site. Runs before `astro dev` and `astro build`.
// Source: $COORDINATOR_DIR if set, else a shallow clone of the Coordinator repo in .cache/coordinator.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_URL = 'https://github.com/Kodexa-software/Coordinator.git';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = join(root, '.cache', 'coordinator');

function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 60_000 }).trim();
}

function fail(message) {
  console.error(`sync-coordinator: ${message}`);
  process.exit(1);
}

function source() {
  if (process.env.COORDINATOR_DIR) {
    const dir = resolve(process.env.COORDINATOR_DIR);
    if (!existsSync(join(dir, '.claude-plugin', 'plugin.json'))) {
      fail(`COORDINATOR_DIR (${dir}) has no .claude-plugin/plugin.json. Point it at a Coordinator clone.`);
    }
    return dir;
  }
  try {
    if (existsSync(join(cacheDir, '.git'))) {
      git(['fetch', '--depth', '1', 'origin', 'HEAD'], cacheDir);
      git(['reset', '--hard', 'FETCH_HEAD'], cacheDir);
    } else {
      rmSync(cacheDir, { recursive: true, force: true });
      mkdirSync(dirname(cacheDir), { recursive: true });
      git(['clone', '--depth', '1', REPO_URL, cacheDir], root);
    }
  } catch (error) {
    if (existsSync(join(cacheDir, '.claude-plugin', 'plugin.json'))) {
      console.warn(`sync-coordinator: couldn't update from ${REPO_URL}; using the cached copy.`);
    } else {
      rmSync(cacheDir, { recursive: true, force: true });
      fail(
        `couldn't clone ${REPO_URL} and there's no cached copy.\n` +
          `  ${String(error.stderr || error.message).trim()}\n` +
          '  Check the network, or set COORDINATOR_DIR to a local Coordinator clone.',
      );
    }
  }
  return cacheDir;
}

function writeIfChanged(file, content) {
  mkdirSync(dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

const dir = source();

const { version } = JSON.parse(readFileSync(join(dir, '.claude-plugin', 'plugin.json'), 'utf8'));
if (typeof version !== 'string' || !version) fail(`no version in ${join(dir, '.claude-plugin', 'plugin.json')}.`);

let sha = null;
let date = null;
try {
  // Only when dir is a checkout's root, not a plain folder inside some other repo.
  if (realpathSync(git(['rev-parse', '--show-toplevel'], dir)) !== realpathSync(dir)) throw new Error('not a checkout root');
  sha = git(['rev-parse', 'HEAD'], dir);
  date = git(['log', '-1', '--format=%cI'], dir);
} catch {
  console.warn(`sync-coordinator: ${dir} isn't a git checkout; sha and date are left empty.`);
}

const changelogFile = join(dir, 'CHANGELOG.md');
if (!existsSync(changelogFile)) fail(`no CHANGELOG.md in ${dir}.`);
const changelog = readFileSync(changelogFile, 'utf8').replace(/^\s*# Changelog[^\n]*\n+/, '').trim();

const info = JSON.stringify({ version, sha, date }, null, 2) + '\n';
writeIfChanged(join(root, 'src', 'generated', 'coordinator.json'), info);
writeIfChanged(join(root, 'public', 'coordinator.json'), info);
// sidebar.order 1000 keeps the changelog last; the hand-written pages use lower numbers.
writeIfChanged(
  join(root, 'src', 'content', 'docs', 'docs', 'changelog.md'),
  [
    '---',
    'title: Changelog',
    'description: What changed in each Coordinator release.',
    'sidebar:',
    '  order: 1000',
    '---',
    '',
    '<!-- Generated by scripts/sync-coordinator.mjs from the Coordinator repo. Edit CHANGELOG.md there. -->',
    '',
    changelog,
    '',
  ].join('\n'),
);

console.log(`sync-coordinator: Coordinator ${version}${sha ? ` (${sha.slice(0, 7)})` : ''} from ${dir}`);
